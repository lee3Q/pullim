export function getDemoListenResponse(turnCount: number, theme?: DemoTheme) {
  const t = LISTEN_BY_THEME[theme || "모험가"];
  if (turnCount >= 3) {
    return { ...t.summary, listenComplete: true };
  }
  return t.turns[turnCount] || t.turns[1];
}

